const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const sheet = fs.readFileSync(path.join(root, 'templates/character-sheet.hbs'),'utf8');
const css = fs.readFileSync(path.join(root, 'styles/layout-overhaul.css'),'utf8');
const will = fs.readFileSync(path.join(root, 'scripts/campaign-will.js'),'utf8');
const js = fs.readFileSync(path.join(root, 'scripts/character-sheet.js'),'utf8');
const mainHeader = sheet.slice(sheet.indexOf('<header class="fts-header">'),sheet.indexOf('</header>'));
const summary = mainHeader.slice(mainHeader.indexOf('<div class="fts-fate-summary">'));
assert.doesNotMatch(summary, /fts-will-controls|beginCampaignScene|configureWillNpc|setupCampaignWorldSkills/, 'the resource summary must not include text-heavy GM controls');
assert.match(sheet, /<details class="fts-campaign-settings"/, 'GM options belong in a separate collapsible block');
assert.match(sheet, /<fieldset class="fts-campaign-role">/, 'PC and NPC selections have a separate form group');
assert.match(sheet, /data-action="configureWillPc"/, 'manual legacy PC setup remains available');
assert.match(sheet, /data-action="configureWillNpc"/, 'NPC settings remain available');
assert.doesNotMatch(sheet, /data-action="setupCampaignWorldSkills"/, 'world setup is not character configuration');
assert.match(fs.readFileSync(path.join(root,'scripts/unified-dock.js'),'utf8'), /data-actor-profile/, 'campaign framework action is available in GM dock');
assert.match(css, /\.fate-toolkit-character-sheet \.fts-campaign-action\s*\{[^}]*width:\s*auto/, 'GM action buttons must not inherit 42px icon width');
assert.match(css, /\.fate-toolkit-character-sheet \.fts-shell \{ display: flex; flex-direction: column;/, 'additional header band must not break sheet body layout');
assert.match(css, /\.fate-toolkit-character-sheet \.fts-shell > \.fts-body \{ flex: 1 1 auto;/, 'sheet body must own the remaining height');
assert.match(js, /campaignSettingsOpen:/, 'GM settings open state must persist across actor updates');
assert.match(will, /Hooks\.on\?\.\('createActor'/, 'new actors must be configured when the mode is enabled');
console.log('campaign-sheet-layout.test.cjs OK');
